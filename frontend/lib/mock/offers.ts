/**
 * Stamp the seeds' relative windows into concrete timestamps around `now`.
 * Pure: the same `now` always yields the same offers. Called from
 * `services/offers.ts`; this file never reads the clock itself, so module
 * evaluation stays deterministic.
 */
export function buildOffers(now: number): Offer[] {
  return OFFER_SEEDS.map(({ startsInDays, endsInDays, ...offer }) => ({
    ...offer,
    startsAt: new Date(now + startsInDays * DAY).toISOString(),
    endsAt: new Date(now + endsInDays * DAY).toISOString(),
  }));
}

/** Slugs for routing/`generateStaticParams` — no clock needed. */
export const offerSlugs = OFFER_SEEDS.map((o) => o.slug);
